function media(id: string) {
  return {
    setupImage: `${base}exercises/${id}/setup.jpg`,
    finishImage: `${base}exercises/${id}/finish.jpg`,
    video: `${base}exercises/${id}/how.mp4`,
  }
}

function lift(
  id: string,
  name: string,
  role: ExerciseRole,
  dayGroup: DayGroup,
  equipment: string,
  muscles: string[],
  cues: string[],
  extra: Partial<Exercise> = {},
): Exercise {
  return {
    id,
    name,
    kind: 'lift',
    role,
    dayGroup,
    equipment,
    muscles,
    cues,
    substituteIds: extra.substituteIds ?? [],
    ...media(id),
    ...extra,
  }
}

